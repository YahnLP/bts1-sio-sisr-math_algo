projet = {"A": (3, []), "B": (2, ["A"]), "C": (6, ["B"]), "D": (4, ["A"]), "E": (5, ["D"]), "F": (4, ["C", "E"]), "G": (3, ["B"]), "H": (2, ["F", "G"])}
assert analyse(projet) == (18, {"A": 0, "B": 1, "C": 1, "D": 0, "E": 0, "F": 0, "G": 8, "H": 0}, ["A", "D", "E", "F", "H"])
mig = {"A": (2, []), "B": (4, []), "C": (3, ["A", "B"]), "D": (2, ["C"]), "E": (5, ["B"]), "F": (1, ["D", "E"])}
assert analyse(mig) == (10, {"A": 2, "B": 0, "C": 0, "D": 0, "E": 0, "F": 0}, ["B", "C", "D", "E", "F"])
assert analyse({"X": (5, [])}) == (5, {"X": 0}, ["X"])
assert analyse({"X": (5, []), "Y": (2, [])})[1] == {"X": 0, "Y": 3}
